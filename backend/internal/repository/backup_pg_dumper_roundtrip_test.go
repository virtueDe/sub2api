package repository

import (
	"bytes"
	"context"
	"encoding/json"
	"io"
	"os"
	"os/exec"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// Run only against an explicitly supplied, disposable local container. No
// production DSN is accepted. This exercises real pg_dump, filtering and psql.
func TestPgDumperPostgresRoundTrip(t *testing.T) {
	const container = "sub2api-backup-test-roundtrip"
	configured := os.Getenv("SUB2API_BACKUP_TEST_CONTAINER")
	if configured == "" {
		t.Skip("set SUB2API_BACKUP_TEST_CONTAINER=sub2api-backup-test-roundtrip to run the disposable database test")
	}
	require.Equal(t, container, configured, "only the named disposable backup test container is accepted")
	run := func(database, sql string) string {
		t.Helper()
		cmd := exec.Command("docker", "exec", "-i", container, "psql", "-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-U", "postgres", "-d", database)
		cmd.Stdin = strings.NewReader(sql)
		out, err := cmd.CombinedOutput()
		require.NoError(t, err, "test database command: %s", out)
		return strings.TrimSpace(string(out))
	}
	run("postgres", "DROP DATABASE IF EXISTS backup_source; DROP DATABASE IF EXISTS backup_restored;")
	run("postgres", "CREATE DATABASE backup_source; CREATE DATABASE backup_restored;")
	t.Cleanup(func() {
		run("postgres", "DROP DATABASE IF EXISTS backup_source; DROP DATABASE IF EXISTS backup_restored;")
	})
	image := `{"prompt":"猫\nline\t\\path","request_params":{"prompt":"keep","seed":9007199254740993,"nested":[{"image_url":{"url":"data:image/png;base64,YQ=="}}]},"images":[{"b64_json":"` + strings.Repeat("ABCD", 300000) + `","url":"https://example.test/cat.png","mime_type":"image/png"}],"future":{"cost":0.1234567890123456789}}`
	run("backup_source", `
CREATE TABLE users(id bigint PRIMARY KEY, balance numeric(18,8) NOT NULL);
CREATE TABLE usage_logs(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint REFERENCES users(id), actual_cost numeric(18,8), created_at timestamptz, image_generation jsonb);
CREATE TABLE ops_error_logs(id bigint PRIMARY KEY, image_generation jsonb, user_id bigint REFERENCES users(id), error_message text);
CREATE TABLE ordinary_logs(id bigint PRIMARY KEY, body text);
CREATE FUNCTION copy_marker() RETURNS text LANGUAGE sql AS $body$
SELECT $inner$
COPY public.usage_logs (image_generation) FROM stdin;
{"images":[{"b64_json":"function-body-keep"}]}
\.
$inner$::text;
$body$;
INSERT INTO users VALUES(7,12345.12345678);
INSERT INTO usage_logs(user_id,actual_cost,created_at,image_generation) VALUES(7,0.12345678,'2026-10-30 06:00:00+08','`+image+`'::jsonb);
INSERT INTO usage_logs(user_id,actual_cost,image_generation) VALUES(7,1,NULL),(7,2,'null'::jsonb);
INSERT INTO ops_error_logs VALUES(9,'`+image+`'::jsonb,7,E'keep\nline\ttab\\path');
INSERT INTO ordinary_logs VALUES(1,'data:image/png;base64,UNRELATED-TEXT');
`)
	targetDB := "backup_source"
	dumper, mock := newTestPgDumper(t, func(ctx context.Context, name string, args ...string) *exec.Cmd {
		forward := []string{"exec", "-i", container, name, "-U", "postgres", "-d", targetDB}
		for i := 0; i < len(args); i++ {
			if args[i] == "-h" || args[i] == "-p" || args[i] == "-U" || args[i] == "-d" {
				i++
				continue
			}
			forward = append(forward, args[i])
		}
		return exec.CommandContext(ctx, "docker", forward...)
	})
	expectBackupMigrationLock(mock)
	reader, err := dumper.Dump(context.Background())
	require.NoError(t, err)
	dump, err := io.ReadAll(reader)
	require.NoError(t, err)
	expectBackupMigrationUnlock(mock)
	require.NoError(t, reader.Close())
	require.NoError(t, mock.ExpectationsWereMet())
	require.Less(t, len(dump), 100000, "large image bytes must not enter the backup")
	require.Contains(t, string(dump), "function-body-keep")
	require.Contains(t, string(dump), "UNRELATED-TEXT")
	// Dumping must not change either source table.
	require.Equal(t, "1200000", run("backup_source", "SELECT length(image_generation->'images'->0->>'b64_json') FROM usage_logs WHERE id=1;"))
	require.Equal(t, "1200000", run("backup_source", "SELECT length(image_generation->'images'->0->>'b64_json') FROM ops_error_logs WHERE id=9;"))
	targetDB = "backup_restored"
	require.NoError(t, dumper.Restore(context.Background(), bytes.NewReader(dump)))
	var got map[string]any
	require.NoError(t, json.Unmarshal([]byte(run(targetDB, `SELECT json_build_object(
 'balance',(SELECT balance::text FROM users WHERE id=7),
 'cost',(SELECT actual_cost::text FROM usage_logs WHERE id=1),
 'time',(SELECT extract(epoch from created_at)::bigint FROM usage_logs WHERE id=1),
 'usage_rows',(SELECT count(*) FROM usage_logs),
 'error_rows',(SELECT count(*) FROM ops_error_logs),
 'sql_null',(SELECT image_generation IS NULL FROM usage_logs WHERE id=2),
 'json_null',(SELECT image_generation='null'::jsonb FROM usage_logs WHERE id=3),
 'no_output_b64',NOT EXISTS(SELECT 1 FROM usage_logs WHERE image_generation->'images'->0 ? 'b64_json'),
 'error_no_output_b64',NOT EXISTS(SELECT 1 FROM ops_error_logs WHERE image_generation->'images'->0 ? 'b64_json'),
 'input_removed',(SELECT image_generation#>>'{request_params,nested,0,image_url,url}' FROM usage_logs WHERE id=1),
 'prompt',(SELECT image_generation->>'prompt' FROM usage_logs WHERE id=1),
 'url',(SELECT image_generation#>>'{images,0,url}' FROM usage_logs WHERE id=1),
 'seed',(SELECT image_generation#>>'{request_params,seed}' FROM usage_logs WHERE id=1),
 'precision',(SELECT image_generation#>>'{future,cost}' FROM usage_logs WHERE id=1),
 'error_message',(SELECT error_message FROM ops_error_logs WHERE id=9),
 'function_unchanged',position('function-body-keep' IN copy_marker())>0
);`)), &got))
	require.Equal(t, "12345.12345678", got["balance"])
	require.Equal(t, "0.12345678", got["cost"])
	require.Equal(t, float64(1793311200), got["time"])
	require.Equal(t, float64(3), got["usage_rows"])
	require.Equal(t, float64(1), got["error_rows"])
	for _, key := range []string{"sql_null", "json_null", "no_output_b64", "error_no_output_b64", "function_unchanged"} {
		require.Equal(t, true, got[key], key)
	}
	require.Equal(t, "[IMAGE_DATA_OMITTED]", got["input_removed"])
	require.Equal(t, "猫\nline\t\\path", got["prompt"])
	require.Equal(t, "https://example.test/cat.png", got["url"])
	require.Equal(t, "9007199254740993", got["seed"])
	require.Equal(t, "0.1234567890123456789", got["precision"])
	require.Equal(t, "keep\nline\ttab\\path", got["error_message"])
	require.Equal(t, "4", run(targetDB, "INSERT INTO usage_logs(user_id) VALUES(7) RETURNING id;"))
	// SQL errors must fail the restore and roll back earlier writes.
	err = dumper.Restore(context.Background(), strings.NewReader("UPDATE users SET balance=0; SELECT missing_backup_column;"))
	require.Error(t, err)
	require.Equal(t, "12345.12345678", run(targetDB, "SELECT balance::text FROM users WHERE id=7;"))
}
